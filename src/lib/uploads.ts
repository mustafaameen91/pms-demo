import "server-only";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { createT, type T } from "@/i18n/translate";

// Files live on the server's own disk. Back up UPLOAD_DIR together with the database.
const ROOT = path.resolve(process.env.UPLOAD_DIR ?? "./uploads");

export const MAX_RECEIPT_BYTES = 8 * 1024 * 1024;

const TYPES = {
  "application/pdf": { ext: "pdf", magic: (b: Buffer) => b.subarray(0, 5).toString("latin1") === "%PDF-" },
  "image/jpeg": { ext: "jpg", magic: (b: Buffer) => b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff },
  "image/png": {
    ext: "png",
    magic: (b: Buffer) => b.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])),
  },
  "image/webp": {
    ext: "webp",
    magic: (b: Buffer) => b.subarray(0, 4).toString("latin1") === "RIFF" && b.subarray(8, 12).toString("latin1") === "WEBP",
  },
} as const;

export type ReceiptType = keyof typeof TYPES;
export const RECEIPT_ACCEPT = Object.keys(TYPES).join(",");

export type SavedFile = { path: string; name: string; type: ReceiptType };

type SaveOptions = {
  maxBytes: number;
  allowed: ReceiptType[];
  tooBig: string;
  wrongType: string;
  fallbackName: string;
};

/**
 * Validates and stores an uploaded file. The type is decided from the file's
 * first bytes, not from its name or the browser's claim. Errors in `t`'s language.
 */
async function saveUpload(workspaceId: string, file: File, o: SaveOptions, t: T): Promise<SavedFile | { error: string }> {
  if (file.size === 0) return { error: t("The file is empty.") };
  if (file.size > o.maxBytes) return { error: t(o.tooBig) };
  const bytes = Buffer.from(await file.arrayBuffer());
  const type = o.allowed.find((k) => TYPES[k].magic(bytes));
  if (!type) return { error: t(o.wrongType) };

  // Workspace ids are generated by us (no slashes), file names are random.
  const relative = path.join(workspaceId, `${randomUUID()}.${TYPES[type].ext}`);
  const absolute = resolveInside(relative);
  await mkdir(path.dirname(absolute), { recursive: true });
  await writeFile(absolute, bytes);
  const name = path.basename(file.name).slice(0, 200) || `${o.fallbackName}.${TYPES[type].ext}`;
  return { path: relative, name, type };
}

export function saveReceipt(workspaceId: string, file: File, t: T = createT("en", {})) {
  return saveUpload(
    workspaceId,
    file,
    {
      maxBytes: MAX_RECEIPT_BYTES,
      allowed: Object.keys(TYPES) as ReceiptType[],
      tooBig: "Receipts can be at most 8 MB.",
      wrongType: "Receipts must be a PDF, JPG, PNG or WebP file.",
      fallbackName: "receipt",
    },
    t,
  );
}

export const MAX_IMAGE_BYTES = 2 * 1024 * 1024;
export const IMAGE_ACCEPT = "image/png,image/jpeg,image/webp";

/** A company logo or stamp: PNG, JPG or WebP, up to 2 MB. */
export function saveImage(workspaceId: string, file: File, t: T = createT("en", {})) {
  return saveUpload(
    workspaceId,
    file,
    {
      maxBytes: MAX_IMAGE_BYTES,
      allowed: ["image/png", "image/jpeg", "image/webp"],
      tooBig: "Images can be at most 2 MB.",
      wrongType: "Images must be PNG, JPG or WebP.",
      fallbackName: "image",
    },
    t,
  );
}

export async function readStoredFile(relative: string) {
  return readFile(resolveInside(relative));
}

export async function deleteStoredFile(relative: string | null | undefined) {
  if (!relative) return;
  await unlink(resolveInside(relative)).catch(() => {});
}

/** Refuses any path that would escape the upload folder. */
function resolveInside(relative: string) {
  const absolute = path.resolve(ROOT, relative);
  if (!absolute.startsWith(ROOT + path.sep)) throw new Error("Invalid file path");
  return absolute;
}
